/*
# Orders and Mercado Pago payments

1. New tables
- `orders`: order header created by the checkout Edge Function.
- `order_items`: immutable snapshot of product name, SKU and price at purchase time.
2. Security
- RLS enabled with no public policies; only the service role used by Edge Functions can access them.
3. Payment application
- `apply_mp_payment` updates the order and discounts stock only once when a payment is approved.
*/

CREATE TABLE IF NOT EXISTS public.orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  external_reference text NOT NULL UNIQUE,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','authorized','in_process','rejected','cancelled','refunded','charged_back','failed')),
  payment_id text,
  payment_method text,
  stock_deducted boolean NOT NULL DEFAULT false,
  total numeric(12,2) NOT NULL CHECK (total >= 0),
  currency text NOT NULL DEFAULT 'PEN',
  customer_name text,
  customer_email text,
  customer_phone text,
  mp_preference_id text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.order_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id uuid NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  product_id uuid REFERENCES public.products(id) ON DELETE SET NULL,
  product_name text NOT NULL,
  sku text NOT NULL,
  unit_price numeric(12,2) NOT NULL CHECK (unit_price >= 0),
  quantity integer NOT NULL CHECK (quantity > 0),
  subtotal numeric(12,2) NOT NULL CHECK (subtotal >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS orders_status_idx ON public.orders(status);
CREATE INDEX IF NOT EXISTS orders_created_idx ON public.orders(created_at DESC);
CREATE INDEX IF NOT EXISTS order_items_order_idx ON public.order_items(order_id);

ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.orders, public.order_items TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.orders_order_number_seq TO service_role;

CREATE OR REPLACE FUNCTION public.apply_mp_payment(
  p_external_reference text,
  p_payment_id text,
  p_status text,
  p_payment_method text
) RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_order_id uuid;
  v_previous_status text;
  v_stock_deducted boolean;
  v_new_status text := p_status;
BEGIN
  SELECT id, status, stock_deducted INTO v_order_id, v_previous_status, v_stock_deducted
  FROM public.orders
  WHERE external_reference = p_external_reference
  FOR UPDATE;

  IF v_order_id IS NULL THEN
    RETURN;
  END IF;

  -- Ignore late notifications that would move a settled payment back to an earlier state.
  IF v_previous_status = 'approved' AND p_status IN ('pending','in_process','authorized','rejected') THEN
    v_new_status := 'approved';
  END IF;
  IF v_previous_status IN ('refunded','charged_back') AND p_status IN ('pending','in_process','authorized','approved') THEN
    v_new_status := v_previous_status;
  END IF;

  UPDATE public.orders
  SET status = v_new_status,
      payment_id = p_payment_id,
      payment_method = p_payment_method,
      updated_at = now()
  WHERE id = v_order_id;

  IF v_new_status = 'approved' AND NOT v_stock_deducted THEN
    UPDATE public.products p
    SET stock = greatest(p.stock - oi.quantity, 0),
        updated_at = now()
    FROM public.order_items oi
    WHERE oi.order_id = v_order_id AND p.id = oi.product_id;

    UPDATE public.orders SET stock_deducted = true WHERE id = v_order_id;
  ELSIF v_new_status IN ('refunded','charged_back') AND v_stock_deducted THEN
    UPDATE public.products p
    SET stock = p.stock + oi.quantity,
        updated_at = now()
    FROM public.order_items oi
    WHERE oi.order_id = v_order_id AND p.id = oi.product_id;

    UPDATE public.orders SET stock_deducted = false WHERE id = v_order_id;
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.apply_mp_payment(text, text, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.apply_mp_payment(text, text, text, text) TO service_role;
